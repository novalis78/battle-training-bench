#!/usr/bin/env python3
"""
Reproducibility incident log of the edition: every scoring batch that was discarded and replayed, or every build whose
generated numbers were found stale, while the report was built; with the date, the cause, what was discarded, what
replaced it and the commit that closed it. A correction is harmless when it is rule-governed and visible.
  python3 research/paper/incidents.py [--edition v1.1]  ->  research/paper/generated/incidents.json, incidents.tex
"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
argv = sys.argv[1:]
EDITION = argv[argv.index("--edition") + 1] if "--edition" in argv else "v1.1"
GEN = f"{ROOT}/research/paper/generated"
INCIDENTS = [
    {"id": "I1", "date": "2026-11-03 to 2026-11-04", "detected": "2026-11-04T14:05Z", "kind": "data replaced",
     "cause": "the export tool kept 0-byte files from failed R2 downloads of controller sources and never retried them; 84 sources were empty",
     "discarded": "18,816 game records played against empty controllers (2,688 on the Mac, 16,128 on the scoring machine), which had scored like the idle baseline",
     "replaced_by": "the same games replayed from the re-fetched sources under the unchanged protocol; the exporter now treats an empty download as a failed fetch",
     "scores_affected": "two ladder entrants' provisional scores in intermediate builds of 3-4 November; no published number", "commit": "e2994e9"},
    {"id": "I2", "date": "2026-11-03T22:47Z", "detected": "2026-11-03T23:05Z", "kind": "build with stale numbers",
     "cause": "the scoring chain's clean-worktree checkout was refused once controlled-edition.json became a tracked file, and the chain continued with the 19:12 UTC scores",
     "discarded": "one intermediate build (not published)", "replaced_by": "a rescore at 23:13 UTC with the worktree reset before the checkout; the chain was fixed",
     "scores_affected": "none published", "commit": "37a57d8"},
    {"id": "I3", "date": "2026-11-03 to 2026-11-04", "detected": "2026-11-04T16:30Z (fifth outside review)", "kind": "stale generated table",
     "cause": "the night chains ran commitments.py and figures.py but not manifest.py, so the manifest appendix carried the 3 November Merkle roots in the 4 November build",
     "discarded": "the manifest table of builds 0594fa2 and earlier that day", "replaced_by": "manifest.py regenerated; the build sequence is commitments.py, figures.py, manifest.py, latexmk",
     "scores_affected": "none; roots in the main text were current", "commit": "d40894b"},
    {"id": "I4", "date": "2026-11-03 to 2026-11-04", "detected": "2026-11-04T16:30Z", "kind": "stale result file",
     "cause": "the chain copied results.json and scores.csv back from the scoring worktree but not versions.json, which stayed at its 3 November state",
     "discarded": "the learning-curve input of builds before d40894b (one regression example named a wrong version)", "replaced_by": "the 4 November versions.json; the chain copies all three files",
     "scores_affected": "none; learning curves only", "commit": "d40894b"},
]
os.makedirs(GEN, exist_ok=True)
json.dump({"edition": EDITION, "incidents": INCIDENTS}, open(f"{GEN}/incidents.json", "w"), indent=1)
def t(x): return str(x).replace("_", "\\_").replace("%", "\\%")
with open(f"{GEN}/incidents.tex", "w") as fh:
    fh.write("% generated by research/paper/incidents.py; do not edit\n")
    fh.write("\\begin{tabular}{@{}p{0.03\\textwidth}p{0.12\\textwidth}p{0.3\\textwidth}p{0.22\\textwidth}p{0.22\\textwidth}p{0.06\\textwidth}@{}}\\toprule\n")
    fh.write("Id & Date (detected) & Cause & Discarded & Replaced by & Commit \\\\ \\midrule\n")
    for i in INCIDENTS:
        fh.write(f"{i['id']} & {t(i['date'])} ({t(i['detected'][:10])}) & {t(i['cause'])} & {t(i['discarded'])} & {t(i['replaced_by'])} & \\texttt{{{i['commit']}}} \\\\\n")
    fh.write("\\bottomrule\n\\end{tabular}\n")
print("incidents written", f"{GEN}/incidents.json", len(INCIDENTS))
